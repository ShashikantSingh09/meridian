// Writes src/lib/brand-marks.ts: the few logos the app shows, copied out of open icon sets so
// that none of those sets is a dependency. To add a service, add it below, put the sets in a
// folder with `npm i --prefix <folder> --ignore-scripts @iconify-json/logos @iconify-json/simple-icons
// @iconify-json/devicon @iconify-json/vscode-icons`, then run `node scripts/brands.mjs <folder>`.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const load = (set) => JSON.parse(readFileSync(join(process.argv[2], "node_modules/@iconify-json", set, "icons.json"), "utf8"));
const sets = Object.fromEntries(["logos", "simple-icons", "devicon", "vscode-icons"].map((s) => [s, load(s)]));

/** App id, then where its logo comes from. */
const MARKS = {
  // AI
  "claude-code": "logos:claude-icon",
  anthropic: "logos:claude-icon",
  codex: "logos:openai-icon",
  openai: "logos:openai-icon",
  gemini: "logos:google-gemini-icon",
  xai: "logos:grok-icon",
  deepseek: "logos:deepseek-icon",
  openrouter: "logos:openrouter-icon",
  groq: "logos:groq",
  together: "logos:togetherai-icon",
  mistral: "logos:mistral-ai-icon",
  ollama: "logos:ollama",
  lmstudio: "simple-icons:lmstudio",
  elevenlabs: "logos:elevenlabs-icon",
  cartesia: "logos:cartesia-icon",
  deepgram: "logos:deepgram-icon",
  windows: "logos:microsoft-windows-icon",
  vllm: "simple-icons:vllm",
  // Providers
  gmail: "logos:google-gmail",
  calendar: "logos:google-calendar",
  drive: "logos:google-drive",
  outlook: "vscode-icons:file-type-outlook",
  github: "logos:github-icon",
  linear: "logos:linear-icon",
  notion: "logos:notion-icon",
  atlassian: "logos:atlassian",
  clickup: "logos:clickup-icon",
  monday: "logos:monday-icon",
  todoist: "logos:todoist-icon",
  airtable: "logos:airtable",
  intercom: "logos:intercom-icon",
  sentry: "logos:sentry-icon",
  vercel: "logos:vercel-icon",
  figma: "logos:figma",
  canva: "devicon:canva",
  dropbox: "logos:dropbox",
  stripe: "logos:stripe",
  paypal: "logos:paypal",
  slack: "logos:slack-icon",
  asana: "logos:asana-icon",
  hubspot: "logos:hubspot",
  box: "logos:box",
};

const out = {};
for (const [id, source] of Object.entries(MARKS)) {
  const [set, name] = source.split(":");
  const data = sets[set];
  const icon = data.icons[name];
  if (!icon) throw new Error(`no ${source}`);
  out[id] = { w: icon.width ?? data.width ?? 16, h: icon.height ?? data.height ?? 16, body: icon.body };
}

writeFileSync(
  new URL("../src/lib/brand-marks.ts", import.meta.url),
  `// Generated by scripts/brands.mjs. These logos belong to their owners. See docs/DECISIONS.md, D39.
export const MARKS: Record<string, { w: number; h: number; body: string }> = ${JSON.stringify(out, null, 2)};
`,
);
